package Loops;

public class MultiplicationTable {
    public static void main(String[] args) {

        int multi = 6;

        for (int i = 1; i <=10; i++) {

            System.out.print((multi*i)+" ");



        }

        System.out.println();

        int n = 6;

        for (int j = n; j <= 60 ; j = j+6) {

            System.out.print(j+" ");

        }

        System.out.println();

        int num = 8;

        for (int k = num; k <= 10 * num; k= k+num) {

            System.out.print(k);

        }

        System.out.println();

        for (int t = 1; t <= 10; t = t+2) {

            System.out.println(t);

        }




    }
}
